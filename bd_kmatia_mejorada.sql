-- ============================================================================
-- K-MAT IA - MODELO RELACIONAL MEJORADO PARA DIAGRAMAR
--
-- Dialecto: Oracle SQL / Oracle SQL Developer Data Modeler.
-- Para Supabase/PostgreSQL convertir VARCHAR2(36) a UUID, NUMBER a NUMERIC
-- cuando corresponda, CHAR(1) S/N a BOOLEAN y TIMESTAMP a TIMESTAMPTZ.
--
-- Este archivo NO reemplaza bd_kmatia.sql; es una versión ampliada para el
-- diagrama relacional y la futura implementación del MVP.
